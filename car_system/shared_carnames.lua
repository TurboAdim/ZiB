function getVehicleModName(veh)
	if (not veh) then return "false" end
	veh = isElement(veh) and (getElementType(veh) == "vehicle") and getElementModel(veh) or tonumber(veh)
	return vehTable[veh] or getVehicleNameFromModel(veh) or "false"
end